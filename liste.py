# ESERCIZIO: Modifica lista numeri

# Crea lista con 5 numeri
numeri = [10, 20, 30, 40, 50]
print("Lista iniziale:", numeri)

# Aggiungi un numero alla fine
numeri.append(60)
print("Dopo append(60):", numeri)

# Sostituisci il terzo numero (indice 2)
numeri[2] = 999
print("Dopo numeri[2] = 999:", numeri)

print("\n--- LISTA FINALE ---")
print("Lista finale:", numeri)
